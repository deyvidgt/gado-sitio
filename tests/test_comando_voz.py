@pytest.mark.parametrize("frase,acao,estado,campos", CASOS, ids=[c[0][:50] for c in CASOS])
def test_frase(frase, acao, estado, campos):
    r = V.montar(V.analisar(frase, HOJE), CTX)
    assert r["acao"] == acao
    obtido = ("salva" if V.pode_salvar(r) else "formulario" if r.get("so_formulario") else
              "info" if r.get("so_info") else "pergunta" if r["perguntas"] else "erro")
    assert obtido == estado, (r["erros"], r["perguntas"])
    assert {k: v for k, v in r["campos"] if k != "Descrição"} == campos
